"""Tests for the per-service rtl-airband config builder.

Background
----------
The MA/SL split-process architecture (docs/rspduo_ma_sl_split.md) ends
the "one combined config, two device blocks, one rtl-airband process"
approach.  Each band gets its own rtl-airband instance with its own
config, generated by ``build_service_config()``.

This module pins the contract that build_service_config emits:

- A complete, parseable-by-rtl-airband config in libconfig syntax
- Exactly ONE device block (no leakage of the other band's tuner)
- A stats_filepath that's per-service (so the watchdog can distinguish)
- An icecast block on a per-service mount (so the dashboard can route)
- Channel outputs rewritten to the per-service mixer name
- Idempotent: re-rendering the same inputs gives the same output

The function is exercised end-to-end against synthetic profile text
that mirrors what production profiles look like post-migration.
"""
from __future__ import annotations

import os
import tempfile
import textwrap
import unittest

from combined_config import (
    build_service_config,
    extract_devices_payload,
)


# Mirror the multi-line layout production profiles use post-migration.
# The single-line ``channels: ( { ... outputs: ( ... ); } );`` form
# collides with replace_outputs_with_mixer's line-based scanner —
# rtl-airband-emitted configs always put each brace/paren on its own
# line, so the function was only designed against that shape.
AIRBAND_PROFILE = textwrap.dedent('''\
    airband = true;
    log_scan_activity = true;
    stats_filepath = "/run/rtl_airband_stats.txt";

    devices:
    ({
      type = "soapysdr";
      device_string = "driver=sdrplay,serial=1809063632,mode=MA,tuner=1";
      sample_rate = 1000000;
      mode = "scan";
      gain = 32.800;

      channels:
      (
        {
          freqs = (121.500, 124.600, 127.700);
          modulation = "am";
          bandwidth = 12000;
          squelch_threshold = -27;

          outputs:
          (
            {
              type = "mixer";
              name = "combined";
            }
          );
        }
      );
    });

    mixers: {
      combined: {
        outputs:
        (
          {
            type = "icecast";
            server = "127.0.0.1";
            port = 8000;
            mountpoint = "ANALOG.mp3";
            username = "source";
            password = "062352";
            name = "SprontPi Radio";
            bitrate = 24;
          }
        );
      };
    };
''')


